def build_gpx_points(lat_start, lng_start, elevation_start, waypoints, start_time=None):
    if start_time is None:
        start_time = datetime(2024, 10, 1, 8, 0, 0)

    points = []
    for i, (d_lat, d_lng, d_ele) in enumerate(waypoints):
        lat = round(lat_start + d_lat, 6)
        lng = round(lng_start + d_lng, 6)
        elevation = elevation_start + d_ele
        ts = start_time + timedelta(minutes=i * 8)
        points.append({
            "lat": lat,
            "lng": lng,
            "elevation": elevation,
            "timestamp": ts,
        })
    return points


async def main():
    db = await get_database()
    collection = db.routes

    print("[Update GPX] 开始为种子路线添加 GPX 轨迹数据...\n")

    updated_count = 0
    for route_name, gpx_config in ROUTE_GPX_DATA.items():
        existing = await collection.find_one({"name": route_name})
        if not existing:
            print(f"  [SKIP] 路线不存在: {route_name}")
            continue

        if existing.get("gpx_points") and len(existing["gpx_points"]) > 0:
            print(f"  [SKIP] {route_name} 已有 {len(existing['gpx_points'])} 个轨迹点，跳过")
            continue

        points = build_gpx_points(
            lat_start=gpx_config["lat_start"],
            lng_start=gpx_config["lng_start"],
            elevation_start=gpx_config["elevation_start"],
            waypoints=gpx_config["waypoints"],
        )

        await collection.update_one(
            {"_id": existing["_id"]},
            {"$set": {"gpx_points": points, "updated_at": datetime.utcnow()}},
        )

        updated_count += 1
        print(f"  [OK] {route_name}: 添加 {len(points)} 个轨迹点")

    print(f"\n[Done] 成功更新 {updated_count} 条路线的 GPX 数据！")


if __name__ == "__main__":
    asyncio.run(main())
